package vartest;

/**
 * 文字列ユーティリティクラス
 */
public class StringUtil {
    
    /**
     * 文字列を大文字に変換するメソッド
     * @param input 入力文字列
     * @return 大文字に変換された文字列
     */
    public String toUpperCase(String input) {
        return input.toUpperCase();
    }
    
    /**
     * 文字列を小文字に変換するメソッド
     * @param input 入力文字列
     * @return 小文字に変換された文字列
     */
    public String toLowerCase(String input) {
        return input.toLowerCase();
    }
}